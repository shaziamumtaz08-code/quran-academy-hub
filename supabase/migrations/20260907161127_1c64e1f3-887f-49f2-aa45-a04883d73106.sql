UPDATE public.noorani_qaida_words w
SET word_text = m.glyph
FROM (VALUES
  ('الف','ا'),('با','ب'),('تا','ت'),('ثا','ث'),('جیم','ج'),
  ('حا','ح'),('خا','خ'),('دال','د'),('ذال','ذ'),('را','ر'),
  ('زا','ز'),('سین','س'),('شین','ش'),('صاد','ص'),('ضاد','ض'),
  ('طا','ط'),('ظا','ظ'),('عین','ع'),('غین','غ'),('فا','ف'),
  ('قاف','ق'),('کاف','ك'),('لام','ل'),('میم','م'),('نون','ن'),
  ('واؤ','و'),('ہا','ہ'),('ہمزہ','ء'),('یا','ی')
) AS m(name, glyph)
WHERE w.word_text = m.name
  AND w.baab_id IN (SELECT id FROM public.noorani_qaida_baabs WHERE baab_number = 1);